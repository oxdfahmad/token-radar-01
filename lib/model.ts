// Token Radar's model, version radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol the radar may rank: pre-token, not a wrapped, staked or
// bridged product of a token that already trades, not an exchange, not a versioned pool.
// The snapshot's watchlist is the floor — every watchlist slug is on the board — and the
// radar adds the pre-token protocols below the floor the watchlist rule itself would keep.
// Live-token protocols are kept apart and shown with their market caps, never mixed in.
//
// Implied value is computed from the snapshot's own figures only:
//
//   implied = tvl_usd x categoryMultiple x growthMult x maturityMult x breadthMult
//
//   categoryMultiple  — the category's market multiple, calibrated from the snapshot's
//                       own live-token protocols: the median market-cap / TVL of the
//                       live protocols in that category, shrunk toward the global median
//                       (3 pseudo-observations) and clamped to [0.05, 1.50]. A category
//                       with no live comparable uses the global median. No name is ever
//                       special-cased; the same function scores every row.
//   growthMult        — 1 + clamp(change_7d, -60, 120) / 100 x 0.5
//   maturityMult      — 0.6 + min(age_days, 1095) / 1095 x 0.4 (age unknown: 365 days)
//   breadthMult       — 1 + 0.02 x min(chains, 5)
//
// Farm plans are derived the same way, from the protocol's own record (category, chains,
// TVL, age): a category action, a second qualifying action, a weekly cadence, a hold,
// a points-page check and a log. Every step states what it costs and how long it takes.

/** One protocol entry: exactly the ten fields the sealed snapshot carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants. The dashboard states them and the detail view shows each row's factors. */
export interface ModelConstants {
  shrink_k: number;
  mult_floor: number;
  mult_cap: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  shrink_k: 3,
  mult_floor: 0.05,
  mult_cap: 1.5,
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  breadth_per_chain: 0.02,
  breadth_max_chains: 5,
};

